"""
Project Work 3 — Concrete Target 2: Merchant-Authorized Shopify (2026-10 GraphQL) -> Maximus/FORGE Bridge
1. Pulls authorized product details, variants, and media via GraphQL 2026-10 (respecting cost limits).
2. Stages and uploads a FORGE/Maximus .glb 3D preview back to Shopify via stagedUploadsCreate (MODEL_3D).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict

from us_egress_client import NetworkRoute, USGatewayEgressClient

SHOPIFY_API_VERSION = "2026-10"

PRODUCT_FETCH_QUERY = """
query GetProductForMaximus($id: ID!) {
  product(id: $id) {
    id
    title
    handle
    descriptionHtml
    vendor
    productType
    variants(first: 50) {
      nodes {
        id
        title
        sku
        price
        selectedOptions {
          name
          value
        }
      }
    }
    media(first: 10) {
      nodes {
        mediaContentType
        ... on MediaImage {
          id
          image {
            url
            width
            height
          }
        }
      }
    }
  }
}
"""

STAGED_UPLOAD_MODEL_3D_MUTATION = """
mutation CreateStagedModel3DUpload($input: [StagedUploadInput!]!) {
  stagedUploadsCreate(input: $input) {
    stagedTargets {
      url
      resourceUrl
      parameters {
        name
        value
      }
    }
    userErrors {
      field
      message
    }
  }
}
"""

PRODUCT_CREATE_MEDIA_MUTATION = """
mutation Attach3DModelToProduct($productId: ID!, $media: [CreateMediaInput!]!) {
  productCreateMedia(productId: $productId, media: $media) {
    media {
      id
      mediaContentType
      status
    }
    mediaUserErrors {
      field
      message
    }
  }
}
"""


class ShopifyMaximusBridge:
    """Merchant-authorized GraphQL 2026-10 client routed through the 411 US Egress Client."""

    def __init__(
        self,
        shop_domain: str,
        access_token: str,
        route: NetworkRoute = NetworkRoute.US_EGRESS,
    ) -> None:
        self.shop_domain = shop_domain.replace("https://", "").replace("/", "")
        self.endpoint = f"https://{self.shop_domain}/admin/api/{SHOPIFY_API_VERSION}/graphql.json"
        self.headers = {
            "Content-Type": "application/json",
            "X-Shopify-Access-Token": access_token,
        }
        self.client = USGatewayEgressClient(route=route)

    def graphql(self, query: str, variables: Dict[str, Any]) -> Dict[str, Any]:
        resp = self.client.request(
            "POST",
            self.endpoint,
            headers=self.headers,
            json_body={"query": query, "variables": variables},
        )
        resp.raise_for_status()
        body: Dict[str, Any] = resp.json()
        if "errors" in body and body["errors"]:
            raise RuntimeError(f"Shopify GraphQL Error: {body['errors']}")
        return body

    def fetch_product_for_forge(self, product_gid: str) -> Dict[str, Any]:
        """Retrieves authorized product metadata, variants, and flat-lay images for FORGE/Maximus."""
        result = self.graphql(PRODUCT_FETCH_QUERY, {"id": product_gid})
        product = result.get("data", {}).get("product")
        if not product:
            raise ValueError(f"Product {product_gid} not found or token lacks read_products scope.")
        return {
            "shopify_gid": product["id"],
            "title": product["title"],
            "handle": product["handle"],
            "variants": product["variants"]["nodes"],
            "images": [
                m["image"]["url"]
                for m in product["media"]["nodes"]
                if m.get("mediaContentType") == "IMAGE" and m.get("image")
            ],
            "cost_telemetry": result.get("extensions", {}).get("cost", {}),
        }

    def upload_glb_preview_to_product(self, product_gid: str, glb_path: Path, alt_text: str) -> Dict[str, Any]:
        """
        Executes Shopify's 2-step stagedUploadsCreate -> multipart POST -> productCreateMedia
        for a Draco-compressed .glb 3D model generated by FORGE/Maximus.
        """
        if not glb_path.is_file():
            raise FileNotFoundError(f"GLB asset not found: {glb_path}")

        file_size_bytes = str(glb_path.stat().st_size)  # Mandatory string integer for MODEL_3D in 2026-10

        # Step 1: Request staged upload target
        stage_vars = {
            "input": [
                {
                    "filename": glb_path.name,
                    "mimeType": "model/gltf-binary",
                    "resource": "MODEL_3D",
                    "httpMethod": "POST",
                    "fileSize": file_size_bytes,
                }
            ]
        }
        stage_res = self.graphql(STAGED_UPLOAD_MODEL_3D_MUTATION, stage_vars)
        stage_payload = stage_res["data"]["stagedUploadsCreate"]
        if stage_payload["userErrors"]:
            raise RuntimeError(f"stagedUploadsCreate userErrors: {stage_payload['userErrors']}")

        target = stage_payload["stagedTargets"][0]
        upload_url: str = target["url"]
        resource_url: str = target["resourceUrl"]
        form_fields = {param["name"]: param["value"] for param in target["parameters"]}

        # Step 2: Upload the binary .glb file to the signed cloud storage URL
        with glb_path.open("rb") as f_stream:
            files = {"file": (glb_path.name, f_stream, "model/gltf-binary")}
            up_res = self.client.request(
                "POST",
                upload_url,
                data=form_fields,
                files=files,
                timeout=60.0,
            )
            up_res.raise_for_status()

        # Step 3: Attach the uploaded MODEL_3D resourceUrl to the merchant's product
        attach_vars = {
            "productId": product_gid,
            "media": [
                {
                    "originalSource": resource_url,
                    "mediaContentType": "MODEL_3D",
                    "alt": alt_text,
                }
            ],
        }
        attach_res = self.graphql(PRODUCT_CREATE_MEDIA_MUTATION, attach_vars)
        return attach_res["data"]["productCreateMedia"]

    def close(self) -> None:
        self.client.close()


